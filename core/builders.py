# ---------- PNG / ZIP ----------


def build_png(size: int) -> bytes:
    """PNG valid (gambar noise asli, ter-render) + padding nol SETELAH IEND."""
    def chunk(ctype: bytes, data: bytes) -> bytes:
        return (struct.pack(">I", len(data)) + ctype + data
                + struct.pack(">I", zlib.crc32(ctype + data) & 0xFFFFFFFF))

    def assemble(w: int, h: int, rows: bytes) -> bytes:
        ihdr = struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)
        return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr)
                + chunk(b"IDAT", zlib.compress(rows, 0)) + chunk(b"IEND", b""))

    base = assemble(1, 1, b"\x00\xff\x00\x00")
    if size < len(base) + 1:
        raise GenerationError(
            f"Ukuran minimal PNG valid adalah {len(base) + 1:,} bytes.")
    # dimensi noise agar IDAT mengisi sebagian besar file tanpa oversize
    budget = size - 400
    w = max(1, int((max(1, budget) / 3) ** 0.5))
    rowlen = 1 + 3 * w
    h = max(1, budget // rowlen)
    raw = bytearray()
    for _ in range(h):
        raw += b"\x00" + os.urandom(3 * w)
    blob = assemble(w, h, bytes(raw))
    if len(blob) > size:
        blob = base  # fallback 1x1, sisanya padding
    return blob + b"\x00" * (size - len(blob))


def build_zip(size: int) -> bytes:
    """ZIP valid berisi file teks + padding, bisa dibuka extractor mana pun."""
    parts = {
        "README.txt": ("Dummy file generated by Dummy File Generator for QA testing.\n"
                       "This archive is a valid ZIP container.\n"),
        "data/dummy.txt": "Dummy QA data line A\nDummy QA data line B\n",
    }
    return _zip_exact(parts, size)


# ---------- JPG ----------

_JPG_ASSET = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                          os.pardir, "assets", "sample.jpg")


def _jpg_template() -> bytes:
    with open(_JPG_ASSET, "rb") as f:
        return f.read()


def build_jpg(size: int) -> bytes:
    """JPG valid: gambar asli via Pillow bila ada, fallback template kecil.

    Kedua jalur: byte setelah marker EOI (FF D9) adalah padding nol yang
    diabaikan viewer/preview, jadi file tetap ter-render dan ukurannya persis.
    """
    try:
        from PIL import Image  # opsional — dependency buat gambar asli
    except ImportError:
        Image = None

    if Image is not None:
        budget = size - 600
        w = h = 8
        if budget >= 3 * 8 * 8:
            w = h = int((budget / 3) ** 0.5)
        blob = b""
        for _ in range(8):
            img = Image.frombytes("RGB", (w, h), os.urandom(w * h * 3))
            bio = io.BytesIO()
            img.save(bio, "JPEG", quality=50)
            blob = bio.getvalue()
            if len(blob) <= size:
                break
            w = h = max(8, w // 2)
        if blob and len(blob) <= size:
            return blob + b"\x00" * (size - len(blob))

    tpl = _jpg_template()
    if size < len(tpl) + 1:
        raise GenerationError(
            f"Ukuran minimal JPG valid adalah {len(tpl) + 1:,} bytes "
            "(tanpa Pillow, pakai template) — perbesar ukuran.")
    return tpl + b"\x00" * (size - len(tpl))
