"""Builder file dummy VALID — konten asli yang bisa dibuka/dipreview.

Setiap builder mengembalikan bytes berukuran PERSIS size yang diminta.
Bila size di bawah minimum tipe tsb, raise GenerationError dengan pesan jelas.
"""
import io
import os
import struct
import zipfile
import zlib

from core.errors import GenerationError

# ---------- ZIP (dipakai docx/xlsx/pptx/zip) ----------


def _zip_stored(parts: dict) -> bytes:
    """Rangkai parts (nama -> bytes/str) jadi arsip ZIP_STORED deterministik."""
    bio = io.BytesIO()
    with zipfile.ZipFile(bio, "w", zipfile.ZIP_STORED) as z:
        for name, data in parts.items():
            zi = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            zi.compress_type = zipfile.ZIP_STORED
            z.writestr(zi, data)
    return bio.getvalue()


def _zip_exact(parts: dict, size: int, padname: str = "dummy_padding.bin") -> bytes:
    """Tambah part padding supaya total arsip PERSIS size bytes."""
    def build(pad_len: int) -> bytes:
        p = dict(parts)
        if pad_len > 0:
            p[padname] = b"P" * pad_len
        return _zip_stored(p)

    blob = build(0)
    if len(blob) > size:
        raise GenerationError(f"Ukuran minimal untuk tipe ini adalah {len(blob):,} bytes.")
    pad = size - len(blob)
    for _ in range(6):
        blob = build(pad)
        diff = size - len(blob)
        if diff == 0:
            return blob
        pad += diff
    raise GenerationError("Gagal mencapai ukuran persis untuk arsip ZIP.")


# ---------- PDF ----------

PDF_LINE = ("Dummy QA content line {i:03d} - generated by Dummy File Generator "
            "for upload and preview testing lorem ipsum dolor sit amet")


def _pdf_page_content(lines) -> bytes:
    body = "\n".join(f"({t}) Tj T*" for t in lines)
    return f"BT\n/F1 11 Tf\n13 TL\n72 720 Td\n{body}\nET".encode("latin-1")


def _pdf_obj(num: int, body: bytes) -> bytes:
    return f"{num} 0 obj\n".encode() + body + b"\nendobj\n"


def _pdf_stream_obj(num: int, data: bytes, extra: str = "") -> bytes:
    head = f"{num} 0 obj\n<< {extra}/Length {len(data)} >>\nstream\n".encode()
    return head + data + b"\nendstream\nendobj\n"


def _assemble_pdf(objects: list) -> bytes:
    out = bytearray(b"%PDF-1.7\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for obj in objects:
        offsets.append(len(out))
        out += obj
    xref = len(out)
    n = len(objects) + 1
    out += b"xref\n0 " + str(n).encode() + b"\n0000000000 65535 f \n"
    for off in offsets:
        out += b"%010d 00000 n \n" % off
    out += (f"trailer\n<< /Size {n} /Root 1 0 R >>\n"
            f"startxref\n{xref}\n%%EOF\n").encode()
    return bytes(out)


def _pdf_build_with(n_pages: int, lines: int, pad_len: int) -> bytes:
    """Rangkai PDF dengan n_pages halaman teks + 1 objek padding stream."""
    objects = [
        _pdf_obj(1, b"<< /Type /Catalog /Pages 2 0 R >>"),
        _pdf_obj(2, b"<< /Type /Pages /Kids [" + b" ".join(
            f"{4 + 2 * i} 0 R".encode() for i in range(n_pages)) + b"] /Count "
            + str(n_pages).encode() + b" >>"),
        _pdf_obj(3, b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"),
    ]
    for i in range(n_pages):
        pnum, cnum = 4 + 2 * i, 5 + 2 * i
        page_lines = [PDF_LINE.format(i=j) for j in range(1, lines + 1)]
        objects.append(_pdf_obj(pnum, (
            f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
            f"/Resources << /Font << /F1 3 0 R >> >> /Contents {cnum} 0 R >>").encode()))
        objects.append(_pdf_stream_obj(cnum, _pdf_page_content(page_lines)))
    pad_num = 4 + 2 * n_pages
    objects.append(_pdf_stream_obj(pad_num, b"D" * pad_len, extra="/Type /Dummy "))
    return _assemble_pdf(objects)


def build_pdf(size: int) -> bytes:
    """PDF valid multi-halaman berisi teks, ukuran persis via padding stream."""
    lines = 50 if size >= 8000 else 3
    n_pages = max(1, min((size - 2000) // 6000 + 1, 400))
    blob = _pdf_build_with(n_pages, lines, 0)
    if len(blob) > size:
        n_pages, lines = 1, 3
        blob = _pdf_build_with(n_pages, lines, 0)
        if len(blob) > size:
            raise GenerationError(
                f"Ukuran minimal PDF valid adalah {len(blob):,} bytes — "
                "perbesar ukuran atau matikan 'Isi file valid'.")
    pad = size - len(blob)
    for _ in range(6):
        blob = _pdf_build_with(n_pages, lines, pad)
        diff = size - len(blob)
        if diff == 0:
            return blob
        pad += diff
    raise GenerationError("Gagal mencapai ukuran persis untuk PDF.")


# ---------- OOXML: docx / xlsx / pptx ----------

_XML_DECL = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'


def _content_types(overrides: list) -> str:
    ov = "".join(f'<Override PartName="{p}" ContentType="{c}"/>' for p, c in overrides)
    return (_XML_DECL
            + '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
            + '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
            + '<Default Extension="xml" ContentType="application/xml"/>' + ov + "</Types>")


def _root_rels(target: str) -> str:
    return (_XML_DECL
            + '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            + '<Relationship Id="rId1" '
            'Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" '
            f'Target="{target}"/></Relationships>')


def build_docx(size: int) -> bytes:
    paras = ["Dummy File Generator - QA test document (valid .docx)"]
    paras += [f"Paragraph {i:04d}: lorem ipsum dolor sit amet consectetur adipiscing elit "
              "sed do eiusmod tempor incididunt ut labore et dolore magna aliqua."
              for i in range(1, 21)]
    doc = (_XML_DECL
           + '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
           + "<w:body>"
           + "".join(f'<w:p><w:r><w:t xml:space="preserve">{t}</w:t></w:r></w:p>' for t in paras)
           + "<w:sectPr/></w:body></w:document>")
    parts = {
        "[Content_Types].xml": _content_types([
            ("/word/document.xml",
             "application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml")]),
        "_rels/.rels": _root_rels("word/document.xml"),
        "word/document.xml": doc,
    }
    return _zip_exact(parts, size)


